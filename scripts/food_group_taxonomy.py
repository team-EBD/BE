def canonical_group(raw_group: str) -> str:
    g = (raw_group or "").strip()
    return MERGES.get(g, g)


def canonical_source_group(kind: str, raw_group: str) -> str:
    """원본에서 이름만 같은 서로 다른 식품은 합치지 않는다.

    D 코코아는 조리한 초코 음료(16건), P 코코아는 분말·닙스·스프레드(259건).
    원본 이름은 builder 의 source_names 에 보존한다.
    """
    group = canonical_group(raw_group)
    if kind == "P" and group == "코코아":
        return "코코아가공품"
    return group


def family_for(kind: str, raw_family: str, group: str) -> str:
    """kind: 'D'(음식) | 'P'(가공식품). 군 재배치 → 대분류 매핑 → 기타."""
    group = canonical_source_group(kind, group)
    raw_family = (raw_family or "").strip()
    if group in GROUP_FAMILY_OVERRIDE:
        return GROUP_FAMILY_OVERRIDE[group]
    if kind == "P":
        if raw_family == "즉석식품류":
            return _P_INSTANT_BY_GROUP.get(group, "기타")
        if raw_family == "농산가공식품류":
            return _P_AGRI_BY_GROUP.get(group, "기타")
        return P_FAMILY.get(raw_family, "기타")
    if kind == "D":
        return D_FAMILY.get(raw_family, "기타")
    return "기타"


