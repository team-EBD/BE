# 어미 규칙에서 군명으로 인정할 최소 길이 (1글자 어미 — 국·밥·전 — 는 오탐이 많다)
SUFFIX_MIN_LEN = 2


def resolve_by_suffix(normalized: str, group_names_by_len: list[str]) -> str | None:
    """이름이 군명으로 끝나면 그 군. group_names_by_len 은 긴 이름 우선 정렬된 군명(정규화) 목록."""
    for g in group_names_by_len:
        if len(g) >= SUFFIX_MIN_LEN and normalized.endswith(g):
            return g
    return None


