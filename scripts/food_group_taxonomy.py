def role_for(family: str, group: str) -> str:
    if group in GROUP_ROLE_OVERRIDE:
        return GROUP_ROLE_OVERRIDE[group]
    if family in EXCLUDE_FAMILIES:
        return ROLE_EXCLUDE
    if family == "샐러드·채소·나물" and not group.endswith("샐러드"):
        return ROLE_EXCLUDE  # 나물·무침
    if family == "밥류" and group in COMPANION_GROUPS:
        return ROLE_COMPANION
    if family in SNACK_FAMILIES:
        return ROLE_SNACK
    return ROLE_MEAL


def companion_for(family: str, group: str, role: str) -> str | None:
    """기본 동반 군명. 메인이면서 밥과 먹는 계열이면 쌀밥."""
    if role != ROLE_MEAL:
        return None
    if family in COMPANION_FAMILIES or group in COMPANION_GROUPS_EXTRA:
        return DEFAULT_COMPANION
    return None


